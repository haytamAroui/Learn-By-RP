"""Generate CSS from the canonical tokens and reuse the package's original artwork."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def build():
    data = json.loads((ROOT / 'tokens.json').read_text(encoding='utf-8'))
    blocks = ['/* Generated by build.py from tokens.json. Do not hand edit. */']
    for group, selector in [('foundation', ':root'), ('light', ':root, [data-theme="light"]'), ('dark', '[data-theme="dark"]')]:
        declarations = '\n'.join(f'  --{name}: {value};' for name, value in data[group].items())
        blocks.append(f'{selector} {{\n{declarations}\n}}')
    (ROOT / 'tokens.css').write_text('\n\n'.join(blocks) + '\n', encoding='utf-8')
    (ROOT / 'tokens-data.js').write_text(
        '// Generated by build.py. Do not hand edit.\nwindow.LINGO_TOKENS = '
        + json.dumps(data, indent=2) + ';\n', encoding='utf-8')
    source = (ROOT.parent / 'index.html').read_text(encoding='utf-8')
    build_original_reference(source)
    payload = re.search(r'<script id="lingo-v5-data" type="application/json">(.*?)</script>', source, re.S)
    artwork = json.loads(payload.group(1))['artwork']
    assets = ROOT / 'assets'
    assets.mkdir(exist_ok=True)
    for name, svg in artwork.items():
        # Embedded SVGs inherit their namespace in HTML; standalone files need it.
        if 'xmlns=' not in svg:
            svg = svg.replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ', 1)
        (assets / f'{name}.svg').write_text(svg, encoding='utf-8')
    print(f'Generated {sum(len(data[g]) for g in ("foundation", "light", "dark"))} token declarations; artwork: {", ".join(artwork)}')


def build_original_reference(source):
    """Keep the actual Original 3 markup and cascade, not a hand-rebuilt approximation."""
    styles = re.findall(r'<style(?:\s[^>]*)?>(.*?)</style>', source, re.S)[:3]
    css = '\n\n'.join(styles)
    replacements = {
        '#FDF9F1': 'var(--original-canvas-top)',
        '#F5EFE3': 'var(--original-canvas-bottom)',
        'flex:0 0 384px': 'flex:0 0 var(--original-phone-width)',
        'height:904px': 'height:var(--original-phone-height)',
        'border-radius:57px': 'border-radius:var(--original-device-radius)',
        'height:172px': 'height:var(--original-city-height)',
        'height:163px': 'height:var(--original-lesson-height)',
        'border-radius:28px': 'border-radius:var(--original-feature-radius)',
        'border-radius:24px': 'border-radius:var(--original-card-radius)',
        'border-radius:22px': 'border-radius:var(--original-tile-radius)',
        'border-radius:32px': 'border-radius:var(--original-dock-radius)',
        'min-height:112px': 'min-height:var(--original-tile-height)',
        'width:72px;height:72px': 'width:var(--original-mic-size);height:var(--original-mic-size)',
        'width:104px;height:104px': 'width:var(--original-mic-halo-size);height:var(--original-mic-halo-size)',
        '#E3F5EE': 'var(--original-vocabulary-top)', '#CDEDE1': 'var(--original-vocabulary-bottom)',
        '#E0F2F8': 'var(--original-listening-top)', '#C9E7F2': 'var(--original-listening-bottom)',
        '#FFEAE2': 'var(--original-speaking-top)', '#FFD8CB': 'var(--original-speaking-bottom)',
        '#EFEAFF': 'var(--original-grammar-top)', '#E0D8FF': 'var(--original-grammar-bottom)',
        '#FF7A63': 'var(--original-mic-top)', '#EA4B3B': 'var(--original-mic-bottom)',
    }
    for literal, token in replacements.items():
        assert literal in css, f'Original source changed: missing {literal}'
        css = css.replace(literal, token)
    (ROOT / 'originals.generated.css').write_text(
        '/* Generated from the three Original 3 style layers; component literals mapped to tokens. */\n' + css,
        encoding='utf-8')
    sprite = re.search(r'(<svg xmlns="http://www.w3.org/2000/svg" width="0".*?</svg>)', source, re.S).group(1)
    gallery = re.search(r'(<main class="gallery".*?</main>)', source, re.S).group(1)
    gallery = gallery.replace('id="gallery"', 'id="gallery" inert')
    document = '''<!doctype html>
<html lang="en" data-theme="light"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Lingo Original 3 — source reference</title>
<link rel="stylesheet" href="../assets/fonts/fonts.css">
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="originals.generated.css">
<link rel="stylesheet" href="originals-adapter.css">
</head><body>''' + sprite + gallery + '</body></html>'
    (ROOT / 'originals.html').write_text(document, encoding='utf-8')


if __name__ == '__main__':
    build()
