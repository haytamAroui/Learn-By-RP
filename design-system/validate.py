"""Check token references, theme parity, generated output and supported text pairs."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = json.loads((ROOT / 'tokens.json').read_text(encoding='utf-8'))


def resolve(name, theme, chain=()):
    assert name not in chain, f'Circular token reference: {chain} -> {name}'
    value = {**DATA['foundation'], **DATA[theme]}[name]
    alias = re.fullmatch(r'var\(--([\w-]+)\)', value)
    return resolve(alias[1], theme, (*chain, name)) if alias else value


def luminance(color):
    assert re.fullmatch(r'#[A-Fa-f0-9]{6}', color), color
    channels = [int(color[n:n+2], 16) / 255 for n in (1, 3, 5)]
    linear = [v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in channels]
    return sum(v * w for v, w in zip(linear, (.2126, .7152, .0722)))


def contrast(a, b):
    high, low = sorted((luminance(a), luminance(b)), reverse=True)
    return (high + .05) / (low + .05)


assert set(DATA['light']) == set(DATA['dark']), 'Theme roles differ'
for theme in ('light', 'dark'):
    for name in {**DATA['foundation'], **DATA[theme]}:
        resolve(name, theme)

pairs = [('ink', 'canvas'), ('ink', 'canvas-end'), ('ink', 'surface'),
         ('text-secondary', 'canvas'), ('text-secondary', 'canvas-end'),
         ('text-secondary', 'surface'), ('on-action', 'action'),
         ('on-action', 'action-hover'), ('on-action', 'action-pressed'),
         ('on-accent', 'accent'), ('on-mic', 'mic-bg')]
for activity in ('speaking', 'listening', 'vocabulary', 'grammar'):
    pairs += [(f'{activity}-ink', f'{activity}-soft'), ('text-secondary', f'{activity}-soft')]
for status in ('success', 'warning', 'danger', 'info'):
    pairs.append((status, f'{status}-soft'))

results = []
for theme in ('light', 'dark'):
    for foreground, background in pairs:
        ratio = contrast(resolve(foreground, theme), resolve(background, theme))
        results.append((theme, foreground, background, round(ratio, 2)))
        assert ratio >= 4.5, f'{theme} {foreground}/{background}: {ratio:.2f}:1'

expected = ['/* Generated by build.py from tokens.json. Do not hand edit. */']
for group, selector in [('foundation', ':root'), ('light', ':root, [data-theme="light"]'), ('dark', '[data-theme="dark"]')]:
    declarations = '\n'.join(f'  --{name}: {value};' for name, value in DATA[group].items())
    expected.append(f'{selector} {{\n{declarations}\n}}')
assert (ROOT / 'tokens.css').read_text(encoding='utf-8') == '\n\n'.join(expected) + '\n', 'CSS drift: run build.py'
js = (ROOT / 'tokens-data.js').read_text(encoding='utf-8')
assert js.split('window.LINGO_TOKENS = ', 1)[1] == json.dumps(DATA, indent=2) + ';\n', 'Preview data drift'

all_names = set(DATA['foundation']) | set(DATA['light'])
css = (ROOT / 'components.css').read_text(encoding='utf-8')
local_names = set(re.findall(r'(--[\w-]+)\s*:', css)) | {'--measure', '--exercise-step'}
for name in re.findall(r'var\(--([\w-]+)', css):
    assert name in all_names or '--' + name in local_names, f'Unknown component token: {name}'
print(f'PASS: {len(all_names)} active tokens; theme parity and aliases; generated CSS/JS match; {len(results)} text contrast pairs >= 4.5:1.')
print(f'Lowest verified contrast: {min(results, key=lambda row: row[3])}')
print('Media overlays, illustration colors, focus geometry and interaction behavior require browser inspection.')
